// Writes THIRD_PARTY_LICENSES.txt: name, version, licence and the full
// licence text of every production dependency (package.json "dependencies",
// plus everything they pull in), as resolved from node_modules.
// Fails when a package's licence is not in ALLOWED, so a human looks at it.
//
// Usage: node scripts/third-party-licenses.mjs [output files...]
// (default: THIRD_PARTY_LICENSES.txt at the repo root)

import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Licences that are fine to ship without a closer look (SPDX ids). */
const ALLOWED = new Set(['MIT', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', 'Apache-2.0', '0BSD', 'BlueOak-1.0.0']);

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const LICENSE_FILE = /^(licen[cs]e|copying)(\.|-|$)/i;

function readJson(file) {
  return JSON.parse(readFileSync(file, 'utf8'));
}

/** Node-style lookup: <dir>/node_modules/<name>, then the same in each parent directory. */
function findPackageDir(name, fromDir) {
  let dir = fromDir;
  for (;;) {
    const candidate = join(dir, 'node_modules', name);
    if (existsSync(join(candidate, 'package.json'))) return candidate;
    const parent = dirname(dir);
    if (parent === dir) return null;
    dir = parent;
  }
}

/** The licence as one SPDX-ish string, from "license" or the old "licenses" array. */
function licenseOf(pkg) {
  const l = pkg.license;
  if (typeof l === 'string') return l.trim();
  if (l && typeof l.type === 'string') return l.type.trim();
  if (Array.isArray(pkg.licenses)) {
    const types = pkg.licenses.map((x) => (typeof x === 'string' ? x : x?.type)).filter(Boolean);
    if (types.length > 0) return types.length === 1 ? types[0] : `(${types.join(' OR ')})`;
  }
  return 'UNKNOWN';
}

/** True when a simple SPDX expression is satisfied by ALLOWED ("A OR B": either; "A AND B": both). */
function isAllowed(expression) {
  const clean = expression.replace(/[()]/g, ' ').trim();
  return clean
    .split(/\s+OR\s+/i)
    .some((option) => option.split(/\s+AND\s+/i).every((id) => ALLOWED.has(id.trim())));
}

function licenseText(dir) {
  const files = readdirSync(dir).filter((f) => LICENSE_FILE.test(f)).sort();
  if (files.length === 0) return null;
  return files.map((f) => readFileSync(join(dir, f), 'utf8').replace(/\r\n?/g, '\n').trimEnd()).join('\n\n');
}

/** Every production package reachable from the root package.json, keyed by name@version. */
function collect() {
  const found = new Map();
  const missing = [];
  const visit = (name, fromDir, optional) => {
    const dir = findPackageDir(name, fromDir);
    if (!dir) {
      if (!optional) missing.push(name);
      return;
    }
    const pkg = readJson(join(dir, 'package.json'));
    const key = `${pkg.name}@${pkg.version}`;
    if (found.has(key)) return;
    found.set(key, { name: pkg.name, version: pkg.version, license: licenseOf(pkg), dir });
    for (const dep of Object.keys(pkg.dependencies ?? {})) visit(dep, dir, false);
    for (const dep of Object.keys(pkg.optionalDependencies ?? {})) visit(dep, dir, true);
  };
  const root = readJson(join(ROOT, 'package.json'));
  for (const dep of Object.keys(root.dependencies ?? {})) visit(dep, ROOT, false);
  for (const dep of Object.keys(root.optionalDependencies ?? {})) visit(dep, ROOT, true);
  const packages = [...found.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
  return { packages, missing };
}

function main() {
  const { packages, missing } = collect();
  if (missing.length > 0) {
    console.error(`Not installed: ${missing.join(', ')}. Run "npm install" first.`);
    process.exit(1);
  }
  const flagged = packages.filter((p) => !isAllowed(p.license));
  if (flagged.length > 0) {
    console.error('These production dependencies have a licence outside the allowlist; a human must review them:');
    for (const p of flagged) console.error(`  ${p.name}@${p.version}: ${p.license}`);
    console.error(`Allowed: ${[...ALLOWED].join(', ')} (edit ALLOWED in scripts/third-party-licenses.mjs after review).`);
    process.exit(1);
  }

  const rule = '='.repeat(78);
  const parts = [
    'Third-party software in Gatehouse',
    '',
    'Gatehouse includes the open-source packages below. Each is listed with its',
    'version, licence and licence text as shipped by its authors.',
    'Generated by scripts/third-party-licenses.mjs; do not edit by hand.',
  ];
  for (const p of packages) {
    const text = licenseText(p.dir);
    parts.push(
      '',
      rule,
      `${p.name} ${p.version}`,
      `License: ${p.license}`,
      rule,
      '',
      text ?? `(No LICENSE/LICENCE/COPYING file was found in the package; its licence field is "${p.license}".)`,
    );
  }
  const output = parts.join('\n') + '\n';

  const targets = process.argv.slice(2);
  for (const target of targets.length > 0 ? targets : ['THIRD_PARTY_LICENSES.txt']) {
    const file = resolve(ROOT, target);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, output);
    console.log(`Wrote ${target}`);
  }
  for (const p of packages) console.log(`  ${p.name}@${p.version}  ${p.license}`);
}

main();
